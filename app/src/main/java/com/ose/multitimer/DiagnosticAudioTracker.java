package com.ose.multitimer;

import android.os.SystemClock;

import java.util.HashMap;
import java.util.Map;
import java.util.Objects;

/**
 * Correlates asynchronous audio-player callbacks with diagnostic event IDs.
 *
 * <p>One timer event can produce more than one audio action.  For example, a
 * profile can request both a beep and spoken elapsed time.  The event is
 * therefore considered complete only after every registered action completes.
 * A single failed action fails the event.  This prevents a successful TTS
 * callback from hiding a failed beep, and prevents a beep callback from being
 * mistaken for proof that speech was heard.</p>
 *
 * <p>The tracker deliberately knows nothing about SQLite.  The supplied sink
 * is the narrow boundary back into {@link TimingService}; this makes the
 * bookkeeping unit-testable without Android audio hardware or a database.</p>
 */
final class DiagnosticAudioTracker implements AutoCloseable {
    /** Receives durable state transitions generated by audio callbacks. */
    interface TransitionSink {
        /** Records one transition with callback-time wall and monotonic clocks. */
        void record(
                String eventId,
                DiagnosticEvent.State state,
                long wallMillis,
                long elapsedMillis,
                String detail);
    }

    /** Supplies timestamps at the moment a player callback arrives. */
    interface TimeSource {
        /** Returns the current wall-clock timestamp. */
        long wallMillis();

        /** Returns the current monotonic timestamp. */
        long elapsedMillis();
    }

    private final Object lock = new Object();
    private final Map<String, PendingAudio> pending = new HashMap<>();
    private final TransitionSink sink;
    private final TimeSource timeSource;
    private boolean closed;

    DiagnosticAudioTracker(TransitionSink sink) {
        this(sink, new TimeSource() {
            @Override
            public long wallMillis() {
                return System.currentTimeMillis();
            }

            @Override
            public long elapsedMillis() {
                return SystemClock.elapsedRealtime();
            }
        });
    }

    /** Constructor with an injectable clock so state transitions can be unit-tested exactly. */
    DiagnosticAudioTracker(TransitionSink sink, TimeSource timeSource) {
        this.sink = Objects.requireNonNull(sink, "sink");
        this.timeSource = Objects.requireNonNull(timeSource, "timeSource");
    }

    /**
     * Registers the number of player actions that must complete for one event.
     *
     * <p>Registration occurs before TimingService calls either player.  That
     * ordering matters because Android may invoke a callback very quickly on a
     * different thread.</p>
     */
    void register(String eventId, int actionCount) {
        if (eventId == null || actionCount <= 0) {
            return;
        }
        synchronized (lock) {
            if (closed) {
                return;
            }
            PendingAudio existing = pending.get(eventId);
            if (existing == null) {
                pending.put(eventId, new PendingAudio(actionCount));
            } else {
                // A duplicate registration is unusual, but adding the count
                // is safer than silently declaring an action complete early.
                existing.requiredActions += actionCount;
            }
        }
    }

    /** Records the first callback indicating that at least one action started. */
    void onStarted(String eventId, String detail) {
        if (eventId == null) {
            return;
        }
        boolean shouldRecord;
        synchronized (lock) {
            PendingAudio audio = pending.get(eventId);
            if (closed || audio == null || audio.failed || audio.started) {
                return;
            }
            audio.started = true;
            shouldRecord = true;
        }
        if (shouldRecord) {
            record(eventId, DiagnosticEvent.State.AUDIO_STARTED, detail);
        }
    }

    /** Records one normal action completion and closes the event when all finish. */
    void onCompleted(String eventId, String detail) {
        if (eventId == null) {
            return;
        }
        boolean completeEvent = false;
        synchronized (lock) {
            PendingAudio audio = pending.get(eventId);
            if (closed || audio == null || audio.failed) {
                return;
            }
            if (audio.completedActions < audio.requiredActions) {
                audio.completedActions++;
            }
            if (audio.completedActions >= audio.requiredActions) {
                pending.remove(eventId);
                completeEvent = true;
            }
        }
        if (completeEvent) {
            record(eventId, DiagnosticEvent.State.COMPLETED, detail);
        }
    }

    /** Records a terminal audio failure and forgets the now-finished tracker entry. */
    void onFailed(String eventId, String detail) {
        if (eventId == null) {
            return;
        }
        boolean shouldRecord;
        synchronized (lock) {
            PendingAudio audio = pending.remove(eventId);
            shouldRecord = !closed && audio != null && !audio.failed;
            if (audio != null) {
                audio.failed = true;
            }
        }
        if (shouldRecord) {
            record(eventId, DiagnosticEvent.State.FAILED, detail);
        }
    }

    /** Returns the number of events still waiting for audio evidence. */
    int pendingCount() {
        synchronized (lock) {
            return pending.size();
        }
    }

    /**
     * Stops accepting callbacks during service teardown.
     *
     * <p>The players are closed before this method is called, so their
     * callbacks have an opportunity to record failures while the ledger is
     * still open.  Any callback arriving afterward is intentionally ignored.</p>
     */
    @Override
    public void close() {
        synchronized (lock) {
            closed = true;
            pending.clear();
        }
    }

    private void record(String eventId, DiagnosticEvent.State state, String detail) {
        sink.record(
                eventId,
                state,
                timeSource.wallMillis(),
                timeSource.elapsedMillis(),
                detail == null ? "" : detail);
    }

    /** Mutable state for one event while its audio actions are outstanding. */
    private static final class PendingAudio {
        private int requiredActions;
        private int completedActions;
        private boolean started;
        private boolean failed;

        private PendingAudio(int requiredActions) {
            this.requiredActions = requiredActions;
        }
    }
}
